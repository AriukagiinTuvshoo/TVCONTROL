package mn.familyscreen.tv.engine

/**
 * Immutable representation of an Android UsageEvent.
 * Abstracted to pure Kotlin so the State Machine can be 100% unit-tested on standard JVM.
 */
data class UsageEventRecord(
    val packageName: String,
    val className: String? = null,
    val eventType: Int,
    val timestamp: Long
)

/**
 * Explicit detection states for foreground application monitoring.
 * Replaces the unsafe fallback to stale active packages.
 */
sealed class ForegroundDetectionState {
    /**
     * Confirmed foreground package with high confidence.
     */
    data class KnownForeground(
        val packageName: String,
        val className: String?,
        val timestamp: Long,
        val activeActivityCount: Int
    ) : ForegroundDetectionState()

    /**
     * Confirmed that no content application is currently active (e.g. screen off or all activities paused).
     */
    data class KnownBackground(
        val lastPackageName: String?,
        val timestamp: Long
    ) : ForegroundDetectionState()

    /**
     * Unknown state due to missing recent events, cold boot before any event,
     * or empty event stream.
     */
    data class Unknown(
        val reason: String,
        val candidatePackage: String? = null
    ) : ForegroundDetectionState()

    /**
     * PACKAGE_USAGE_STATS permission is missing or revoked in AppOps.
     */
    object PermissionMissing : ForegroundDetectionState()
}

/**
 * Explicit enforcement decisions generated by the monitoring engine.
 */
sealed class EnforcementDecision {
    /**
     * Whitelisted content app allowed. Count viewing time.
     */
    data class AllowActiveContent(val packageName: String) : EnforcementDecision()

    /**
     * System UI, Launcher, or background idle. Do not block, do not count viewing time.
     */
    object AllowSystemOrIdle : EnforcementDecision()

    /**
     * Unauthorized app or time quota expired. Trigger Launcher takeover.
     */
    data class EnforceBlock(
        val reason: String,
        val blockedPackage: String?,
        val shouldTriggerLaunch: Boolean
    ) : EnforcementDecision()

    /**
     * Usage Access permission missing. Prompt parent on HUD.
     */
    data class RequestPermission(val reason: String) : EnforcementDecision()
}

/**
 * State machine that processes raw Android UsageEvents chronologically to determine
 * the true current foreground package across Android API 26 through 35.
 *
 * Solves:
 * 1. Multiple Activities in the same package (pausing Activity A while Activity B is resumed
 *    does NOT falsely mark the package as background).
 * 2. API 26-28 (MOVE_TO_FOREGROUND=1, MOVE_TO_BACKGROUND=2) vs
 *    API 29+ (ACTIVITY_RESUMED=1, ACTIVITY_PAUSED=2, ACTIVITY_STOPPED=23).
 * 3. Timestamp collisions and duplicate events from sliding query windows.
 * 4. Missing pause events from killed or crashed activities.
 * 5. Screen interactive state transitions.
 * 6. Explicit System UI exemption checks.
 * 7. Rate-limited enforcement decision making to prevent intent loops.
 */
class UsageEventStateMachine(
    val ownPackageName: String = "mn.familyscreen.tv",
    val systemExemptPackages: Set<String> = DEFAULT_SYSTEM_EXEMPT_PACKAGES
) {
    companion object {
        const val EVENT_MOVE_TO_FOREGROUND = 1      // API 21-28
        const val EVENT_ACTIVITY_RESUMED = 1        // API 29+
        const val EVENT_MOVE_TO_BACKGROUND = 2      // API 21-28
        const val EVENT_ACTIVITY_PAUSED = 2         // API 29+
        const val EVENT_USER_INTERACTION = 7        // API 28+
        const val EVENT_SCREEN_INTERACTIVE = 15     // API 28+
        const val EVENT_SCREEN_NON_INTERACTIVE = 16 // API 28+
        const val EVENT_ACTIVITY_STOPPED = 23       // API 29+

        val DEFAULT_SYSTEM_EXEMPT_PACKAGES = setOf(
            "android",
            "com.android.systemui",
            "com.android.inputmethod.latin",
            "com.google.android.inputmethod.latin",
            "com.android.packageinstaller",
            "com.google.android.packageinstaller",
            "com.android.permissioncontroller",
            "com.google.android.permissioncontroller",
            "com.google.android.katniss" // Android TV Voice Assistant
        )
    }

    // Active activities per package: packageName -> Set of active className
    private val activeActivitiesByPackage = mutableMapOf<String, MutableSet<String>>()
    private val processedEventSignatures = LinkedHashSet<String>()
    private val maxDeduplicationHistory = 500

    private var currentPrimaryPackage: String? = null
    private var currentPrimaryActivity: String? = null
    private var lastResumedTimestamp: Long = 0L
    private var lastEventTimestamp: Long = 0L
    private var isScreenInteractive: Boolean = true

    /**
     * Checks if a package is a system utility or framework component that must
     * NOT be blocked, but should also NOT be charged as child content viewing.
     */
    fun isSystemExempt(packageName: String): Boolean {
        if (packageName.isBlank()) return false
        if (packageName == ownPackageName) return true
        if (systemExemptPackages.contains(packageName)) return true
        if (packageName.contains(".inputmethod.") || packageName.endsWith(".ime")) return true
        return false
    }

    fun setScreenInteractive(interactive: Boolean) {
        this.isScreenInteractive = interactive
    }

    fun getScreenInteractive(): Boolean = isScreenInteractive

    fun getLastEventTimestamp(): Long = lastEventTimestamp

    fun getCurrentPrimaryPackage(): String? = currentPrimaryPackage

    fun getActiveActivityCount(packageName: String): Int {
        return activeActivitiesByPackage[packageName]?.size ?: 0
    }

    /**
     * Ingest and process a list of raw usage events in strict chronological order.
     */
    fun processEvents(events: List<UsageEventRecord>): ForegroundDetectionState {
        // Guarantee chronological sorting regardless of incoming delivery order
        val sorted = events.sortedWith(compareBy({ it.timestamp }, { it.eventType }))

        for (event in sorted) {
            val sig = "${event.packageName}|${event.className}|${event.eventType}|${event.timestamp}"
            if (processedEventSignatures.contains(sig)) {
                continue
            }
            processedEventSignatures.add(sig)
            if (processedEventSignatures.size > maxDeduplicationHistory) {
                val it = processedEventSignatures.iterator()
                if (it.hasNext()) {
                    it.next()
                    it.remove()
                }
            }

            if (event.timestamp > lastEventTimestamp) {
                lastEventTimestamp = event.timestamp
            }

            val pkg = event.packageName
            val cls = if (!event.className.isNullOrBlank()) event.className else "__default__"

            when (event.eventType) {
                EVENT_ACTIVITY_RESUMED -> { // Matches both ACTIVITY_RESUMED and legacy MOVE_TO_FOREGROUND (1)
                    val activities = activeActivitiesByPackage.getOrPut(pkg) { mutableSetOf() }
                    activities.add(cls)

                    // Newly resumed activity takes foreground focus in Android's single-focus window model
                    currentPrimaryPackage = pkg
                    currentPrimaryActivity = event.className
                    lastResumedTimestamp = event.timestamp
                }

                EVENT_ACTIVITY_PAUSED -> { // Matches both ACTIVITY_PAUSED and legacy MOVE_TO_BACKGROUND (2)
                    val activities = activeActivitiesByPackage[pkg]
                    activities?.remove(cls)
                    if (activities.isNullOrEmpty()) {
                        activeActivitiesByPackage.remove(pkg)
                        if (currentPrimaryPackage == pkg) {
                            currentPrimaryPackage = null
                            currentPrimaryActivity = null
                        }
                    }
                }

                EVENT_ACTIVITY_STOPPED -> {
                    val activities = activeActivitiesByPackage[pkg]
                    activities?.remove(cls)
                    if (activities.isNullOrEmpty()) {
                        activeActivitiesByPackage.remove(pkg)
                        if (currentPrimaryPackage == pkg) {
                            currentPrimaryPackage = null
                            currentPrimaryActivity = null
                        }
                    }
                }

                EVENT_SCREEN_NON_INTERACTIVE -> {
                    isScreenInteractive = false
                }

                EVENT_SCREEN_INTERACTIVE -> {
                    isScreenInteractive = true
                }
            }
        }

        return evaluateCurrentState()
    }

    /**
     * Evaluate current foreground state based on accumulated event transitions.
     */
    fun evaluateCurrentState(): ForegroundDetectionState {
        if (!isScreenInteractive) {
            return ForegroundDetectionState.KnownBackground(
                lastPackageName = currentPrimaryPackage,
                timestamp = lastEventTimestamp
            )
        }

        val primary = currentPrimaryPackage
        if (primary != null) {
            val count = activeActivitiesByPackage[primary]?.size ?: 1
            return ForegroundDetectionState.KnownForeground(
                packageName = primary,
                className = currentPrimaryActivity,
                timestamp = lastResumedTimestamp,
                activeActivityCount = count
            )
        }

        if (lastEventTimestamp > 0L) {
            return ForegroundDetectionState.KnownBackground(
                lastPackageName = null,
                timestamp = lastEventTimestamp
            )
        }

        return ForegroundDetectionState.Unknown(
            reason = "NO_EVENTS_YET"
        )
    }

    /**
     * Evaluate enforcement decision given current detection state and time policy.
     * Returns Pair(Decision, activeContentPackageOrNull).
     */
    fun evaluateEnforcement(
        detectionState: ForegroundDetectionState,
        isPackageAllowed: (String) -> Boolean,
        isTimeLimitBlocked: () -> Boolean,
        timeLimitBlockReason: () -> String,
        nowElapsedMs: Long,
        lastEnforcedPackage: String?,
        lastEnforcedTimestampMs: Long,
        throttleWindowMs: Long = 2000L
    ): Pair<EnforcementDecision, String?> {
        return when (detectionState) {
            is ForegroundDetectionState.PermissionMissing -> {
                Pair(EnforcementDecision.RequestPermission("USAGE_ACCESS_PERMISSION_REQUIRED"), null)
            }
            is ForegroundDetectionState.KnownForeground -> {
                val pkg = detectionState.packageName
                if (isSystemExempt(pkg)) {
                    Pair(EnforcementDecision.AllowSystemOrIdle, null)
                } else if (!isPackageAllowed(pkg)) {
                    val isThrottled = (pkg == lastEnforcedPackage) && (nowElapsedMs - lastEnforcedTimestampMs < throttleWindowMs)
                    Pair(
                        EnforcementDecision.EnforceBlock(
                            reason = "UNAUTHORIZED_APP",
                            blockedPackage = pkg,
                            shouldTriggerLaunch = !isThrottled
                        ),
                        null
                    )
                } else {
                    // Package is whitelisted
                    if (isTimeLimitBlocked()) {
                        val reason = timeLimitBlockReason()
                        val isThrottled = (pkg == lastEnforcedPackage) && (nowElapsedMs - lastEnforcedTimestampMs < throttleWindowMs)
                        Pair(
                            EnforcementDecision.EnforceBlock(
                                reason = reason,
                                blockedPackage = pkg,
                                shouldTriggerLaunch = !isThrottled
                            ),
                            null
                        )
                    } else {
                        Pair(EnforcementDecision.AllowActiveContent(pkg), pkg)
                    }
                }
            }
            is ForegroundDetectionState.KnownBackground -> {
                Pair(EnforcementDecision.AllowSystemOrIdle, null)
            }
            is ForegroundDetectionState.Unknown -> {
                // Fail-safe: do not blindly block when state is unknown, but do not bill usage either
                Pair(EnforcementDecision.AllowSystemOrIdle, null)
            }
        }
    }

    /**
     * Reset internal tracking state (e.g. on service recreation or test setup).
     */
    fun reset(initialTimestamp: Long = 0L) {
        activeActivitiesByPackage.clear()
        processedEventSignatures.clear()
        currentPrimaryPackage = null
        currentPrimaryActivity = null
        lastResumedTimestamp = initialTimestamp
        lastEventTimestamp = initialTimestamp
        isScreenInteractive = true
    }
}
